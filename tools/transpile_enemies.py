#!/usr/bin/env python3
"""Generate data/enemies.js: vanilla enemy placements + the per-enemy "can defeat" rules.

The randomizer's logic asks questions like "can the player defeat the enemies in
scene 3, room 6?". Answering that needs the vanilla enemy table
(source/enemizer_list.cpp) and the rule for each enemy type
(source/enemizer_logic.cpp, CanDefeatEnemy(enemyId)).

Usage:
    python3 tools/transpile_enemies.py /path/to/OoT3D_Randomizer/source > data/enemies.js
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from transpile_logic import load_enums, strip_comments, translate  # noqa: E402

SRC = sys.argv[1]


def main():
    load_enums(SRC)
    text = strip_comments(open(os.path.join(SRC, "enemizer_list.cpp"), encoding="utf-8").read())
    body = text[text.index("void InitEnemyLocations"):]

    entries = []
    cond = None
    depth = 0
    line_re = re.compile(
        r"enemyLocations\[(\w+)\]\[(\w+)\]\[(\w+)\]\[(\w+)\]\s*=\s*EnemyLocation\((\w+),\s*(.*?)\);"
    )
    for line in body.splitlines():
        m = re.search(r"if \(Dungeon::(\w+)\.(IsVanilla|IsMQ)\(\)\)", line)
        if m:
            cond = m.group(1) + (":v" if m.group(2) == "IsVanilla" else ":mq")
            continue
        m = line_re.search(line)
        if m:
            scene, layer, room, entry, enemy, types = m.groups()
            entries.append([cond, int(scene, 0), int(layer, 0), int(room, 0), int(entry, 0), enemy, "UNDERWATER" in types])
            continue
        if line.strip() == "}" and cond:
            cond = None
        if "AddDuplicateLocations" in line or line.startswith("}"):
            if line.startswith("}"):
                break

    # AddDuplicateLocations(): slots the randomizer copies from other slots.
    dup_re = re.compile(r"enemyLocations\[(\w+)\]\[(\w+)\]\[(\w+)\]\[(\w+)\]\s*=\s*enemyLocations\[(\w+)\]\[(\w+)\]\[(\w+)\]\[(\w+)\];")
    dup_body = text[text.index("void AddDuplicateLocations"):]
    dup_cond = None
    for line in dup_body.splitlines():
        m = re.search(r"if \(Dungeon::(\w+)\.(IsVanilla|IsMQ)\(\)\)", line)
        if m:
            dup_cond = m.group(1) + (":v" if m.group(2) == "IsVanilla" else ":mq")
        m = dup_re.search(line)
        if m:
            dst = [int(x, 0) for x in m.groups()[:4]]
            src = [int(x, 0) for x in m.groups()[4:]]
            for e in list(entries):
                if e[1:5] == src and (dup_cond is None or e[0] in (None, dup_cond)):
                    entries.append([dup_cond or e[0]] + dst + e[5:])
        if line.startswith("}"):
            break

    logic = strip_comments(open(os.path.join(SRC, "enemizer_logic.cpp"), encoding="utf-8").read())
    start = logic.index("bool CanDefeatEnemy(u16 enemyId)")
    sw = logic.index("switch (enemyId)", start)
    i = logic.index("{", sw)
    depth = 0
    j = i
    while True:
        if logic[j] == "{":
            depth += 1
        elif logic[j] == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    switch_js = translate(logic[sw : j + 1] + ";")

    print("// Generated by tools/transpile_enemies.py from gamestabled/OoT3D_Randomizer source. Do not edit.")
    print("// Entries: [dungeon condition, scene, layer, room, actorEntry, enemy, underwater]")
    print("window.OOT_ENEMY_LOCATIONS = [")
    for e in entries:
        print("  " + json.dumps(e, separators=(",", ":")) + ",")
    print("];")
    print("window.OOT_ENEMY_DEFEAT_INIT = function (L) {")
    print("  with (L) {")
    print("    return function (enemyId) {")
    print("      " + switch_js)
    print("      return false;")
    print("    };")
    print("  }")
    print("};")


if __name__ == "__main__":
    main()
