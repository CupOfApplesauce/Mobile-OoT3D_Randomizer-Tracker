#!/usr/bin/env python3
"""Generate data/settings.js: every randomizer setting (name as printed in the
spoiler log, option texts, default) plus the list of logic tricks.

Usage:
    python3 tools/extract_settings.py /path/to/OoT3D_Randomizer/source > data/settings.js
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from transpile_logic import ENUMS, load_enums, strip_comments  # noqa: E402

SRC = sys.argv[1]


def sanitize(s):
    s = s.replace("\\n", " ").replace("\n", " ").strip()
    return re.sub(r" {2,}", " ", s)


def split_args(text):
    """Split a C++ argument list at top-level commas."""
    args, depth, cur, in_str = [], 0, [], False
    i = 0
    while i < len(text):
        c = text[i]
        if in_str:
            cur.append(c)
            if c == "\\":
                cur.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
            cur.append(c)
        elif c in "({[":
            depth += 1
            cur.append(c)
        elif c in ")}]":
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    if "".join(cur).strip():
        args.append("".join(cur).strip())
    return args


def main():
    load_enums(SRC)
    text = strip_comments(open(os.path.join(SRC, "settings.cpp"), encoding="utf-8").read())
    settings = {}
    tricks = []

    for m in re.finditer(r"^Option (\w+)\s*=\s*(Option::(?:U8|Bool)|LogicTrick)\s*\((.*?)\);", text, re.S | re.M):
        var, kind, argtext = m.groups()
        args = split_args(argtext)
        if kind == "LogicTrick":
            tricks.append({"var": var, "name": sanitize(json.loads(args[0]))})
            continue
        if args and re.fullmatch(r"\d+", args[0]):
            args = args[1:]  # indent level
        if not args or not args[0].startswith('"'):
            continue
        name = sanitize(json.loads(args[0]))
        opts_arg = args[1] if len(args) > 1 else ""
        num = re.fullmatch(r"\{\s*NumOpts\((\d+),\s*(\d+)(?:,\s*(\d+))?.*?\)\s*\}", opts_arg)
        if num:
            lo, hi, step = int(num.group(1)), int(num.group(2)), int(num.group(3) or 1)
            options = [str(v) for v in range(lo, hi + 1, step)]
        elif opts_arg.startswith("{"):
            options = [json.loads(s) for s in re.findall(r'"(?:\\.|[^"\\])*"', opts_arg)]
        else:
            options = None
        default = 0
        for i, a in enumerate(args):
            if a.startswith("OptionCategory::") and i + 1 < len(args):
                d = args[i + 1]
                if re.fullmatch(r"\d+", d):
                    default = int(d)
                elif d in ENUMS:
                    default = ENUMS[d]
                break
        settings[var] = {"name": name, "options": options, "default": default, "bool": kind.endswith("Bool")}

    logic_src = strip_comments(open(os.path.join(SRC, "logic.cpp"), encoding="utf-8").read())
    logic_vars = {name: (0 if typ == "u8" else False)
                  for typ, name in re.findall(r"^(bool|u8)\s+(\w+)\s*=", logic_src, re.M)}

    print("// Generated by tools/extract_settings.py from gamestabled/OoT3D_Randomizer source. Do not edit.")
    print("window.OOT_SETTINGS = " + json.dumps(settings, indent=0) + ";")
    print("window.OOT_TRICKS = " + json.dumps(tricks, indent=0) + ";")
    print("// Every variable declared in logic.cpp, with its reset value.")
    print("window.OOT_LOGIC_VARS = " + json.dumps(logic_vars) + ";")


if __name__ == "__main__":
    main()
